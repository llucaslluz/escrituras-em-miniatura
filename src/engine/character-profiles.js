/**
 * Resolve o perfil visual completo de um personagem combinando:
 * 1. Catálogo nominal (`CHARACTER_PROFILES`)
 * 2. Regras contextuais da cena (ex.: Cristo ressurreto vs. ministério mortal,
 *    Morôni mensageiro celeste vs. mortal em M20, cenas da Restauração D01–D14)
 * 3. Opções explícitas passadas pelo construtor da cena
 */
export function getCharacterProfile(sceneId = '', name = '', rawOptions = {}) {
  const cleanName = String(name || '').trim();
  let base = CHARACTER_PROFILES[cleanName];

  if (!base) {
    if (/^(jesus|jesus cristo|cristo|o salvador|senhor|o senhor)$/i.test(cleanName)) {
      base = CHARACTER_PROFILES['Jesus Cristo'];
    } else if (/^(anjo|anjos|mensageiro|mensageiros)/i.test(cleanName)) {
      base = CHARACTER_PROFILES['Gabriel'];
    } else if (/^(soldado|soldados|guarda|guardas)/i.test(cleanName) && /^B(1[4-9]|[23]\d)$/.test(sceneId)) {
      base = CHARACTER_PROFILES['Soldados romanos'];
    } else if (/^(soldado|guarda|guerreiro)/i.test(cleanName)) {
      base = CHARACTER_PROFILES['Jovens guerreiros'];
    } else if (/^(maria|marta|rute|noemi|saria|eva|mulher|cantora|filha|mãe)/i.test(cleanName)) {
      base = CHARACTER_PROFILES['Maria, mãe de Jesus'];
    } else if (/^D(0[1-8]|1[1-3])$/.test(sceneId) || sceneId === 'P14') {
      base = {
        eraStyle: 'restoration',
        garmentStyle: 'restoration-man',
        footwear: 'shoes',
        hairStyle: 'curly-short',
        beardStyle: rawOptions.beard ? 'short-beard' : 'none',
      };
    }
  }

  const profile = { ...(base || {}) };

  // Anjos das escrituras recebem asas emplumadas esculpidas e auréola luminosa
  // (em B11, daniel-den.js constrói suas próprias asas/auréola dedicadas; seres
  // ressurretos como Cristo, Pai, Morôni, João Batista e Pedro/Tiago/João não usam asas).
  if (cleanName === 'Gabriel' || /^(anjo|anjos)\b/i.test(cleanName)) {
    profile.angelWings = sceneId !== 'B11';
    profile.angelHalo = sceneId !== 'B11';
    if (!/^(anjo|anjos)\b/i.test(cleanName) && cleanName !== 'Gabriel') {
      profile.angelWings = false;
      profile.angelHalo = false;
    }
  } else {
    profile.angelWings = false;
    profile.angelHalo = false;
  }

  // Cristo Ressurreto / Celestial vs. Ministério Mortal
  if (cleanName === 'Jesus Cristo' || cleanName === 'Senhor' || cleanName === 'O Senhor') {
    if (RESURRECTED_CHRIST_SCENES.has(sceneId)) {
      profile.eraStyle = 'celestial';
      profile.garmentStyle = 'christ-resurrected';
      profile.robe = '#faf5ea';
      profile.mantle = '#efe3c6';
      profile.sashColor = '#e2c992';
      profile.accentColor = '#dfc17b';
      profile.heavenlyGlow = true;
    } else {
      profile.eraStyle = 'biblical';
      profile.garmentStyle = 'christ-mortal';
      profile.robe = rawOptions.robe || '#f3ead8';
      profile.mantle = rawOptions.mantle || '#8c4635';
      profile.sashColor = profile.mantle;
      profile.heavenlyGlow = true;
    }
  }

  // Morôni como mensageiro ressurreto em D02 / P10 vs. comandante mortal em M13 / M20
  if (cleanName === 'Morôni' && (sceneId === 'D02' || sceneId === 'P10')) {
    profile.eraStyle = 'celestial';
    profile.garmentStyle = 'christ-resurrected';
    profile.robe = '#f8f2e4';
    profile.mantle = '#eadbb8';
    profile.sashColor = '#dec68e';
    profile.armor = false;
    profile.headband = false;
    profile.beard = false;
    profile.beardStyle = 'none';
    profile.heavenlyGlow = true;
  }

  // João Batista como mensageiro celeste em D01
  if (cleanName === 'João Batista' && sceneId === 'D01') {
    profile.eraStyle = 'celestial';
    profile.garmentStyle = 'christ-resurrected';
    profile.robe = '#f6efe0';
    profile.mantle = '#e6d8b8';
    profile.heavenlyGlow = true;
  }

  // Pedro, Tiago e João como mensageiros celestes na restauração do Sacerdócio de Melquisedeque (D11)
  if ((cleanName === 'Pedro' || cleanName === 'Tiago' || cleanName === 'João') && sceneId === 'D11') {
    profile.eraStyle = 'celestial';
    profile.garmentStyle = 'christ-resurrected';
    profile.robe = '#f7f0e2';
    profile.mantle = '#e8dab8';
    profile.sashColor = '#dfc792';
    profile.heavenlyGlow = true;
  }

  // Crianças nunca usam barba ou armadura
  if (/criança|menino|pequenino|jovem/i.test(cleanName) && rawOptions.scale && rawOptions.scale < 0.78) {
    profile.beard = false;
    profile.beardStyle = 'none';
    profile.armor = false;
  }

  return profile;
}
